    private void jTable1MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTable1MouseClicked
        // TODO add your handling code here:
        int r = jTable1.getSelectedRow();
        if (r < 0) {
            return;
        }
        String ma = jTable1.getValueAt(r, 0).toString();
        Object[] d = DB.row("SELECT HoTen, NgaySinh, GioiTinh, SDT FROM NhanVien WHERE MaNV = ?", ma);
        if (d == null) {
            return;
        }
        txtMaNV.setText(ma);
        txtHoTen.setText(DB.str(d[0]));
        txtNgaySinh.setText(DB.str(d[1]));
        if ("Nam".equals(d[2])) {
            rdoNam.setSelected(true);
        } else if (d[2] != null) {
            rdoNu.setSelected(true);
        } else {
            buttonGroup1.clearSelection();
        }
        txtSDT.setText(DB.str(d[3]));
    }//GEN-LAST:event_jTable1MouseClicked

