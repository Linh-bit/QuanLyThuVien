    private void jTable1MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTable1MouseClicked
        // TODO add your handling code here:
        int r = jTable1.getSelectedRow();
        if (r < 0) {
            return;
        }
        String ma = jTable1.getValueAt(r, 0).toString();
        Object[] d = DB.row("SELECT TenSach, TacGia, TheLoai, NamXB, SoLuong FROM Sach WHERE MaSach = ?", ma);
        if (d == null) {
            return;
        }
        txtMaSach.setText(ma);
        txtTenSach.setText(DB.str(d[0]));
        txtTacGia.setText(DB.str(d[1]));
        txtTheLoai.setText(DB.str(d[2]));
        txtNamXB.setText(DB.str(d[3]));
        txtSoLuong.setText(DB.str(d[4]));
    }//GEN-LAST:event_jTable1MouseClicked

