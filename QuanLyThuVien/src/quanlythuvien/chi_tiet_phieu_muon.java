    private void jTable1MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTable1MouseClicked
        // TODO add your handling code here:
        int r = jTable1.getSelectedRow();
        if (r < 0) {
            return;
        }
        String maPM = jTable1.getValueAt(r, 0).toString();
        String maSach = jTable1.getValueAt(r, 1).toString();
        Object[] d = DB.row("SELECT NgayTra, SoLuongMuon FROM ChiTietPhieuMuon WHERE MaPM = ? AND MaSach = ?",
                maPM, maSach);
        if (d == null) {
            return;
        }
        txtMaPM.setText(maPM);
        txtMaSach.setText(maSach);
        txtNgayTra.setText(DB.str(d[0]));
        txtSoLuongMuon.setText(DB.str(d[1]));
    }//GEN-LAST:event_jTable1MouseClicked

